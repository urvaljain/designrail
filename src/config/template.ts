import { stringify } from "yaml";
import { ADAPTER_IDS, CONFIG_SCHEMA_VERSION, type DesignRailConfig } from "./schema.js";

const y = (value: unknown): string => stringify(value, { lineWidth: 0 }).trimEnd();

function block(value: unknown, indent: number): string {
  const pad = " ".repeat(indent);
  return y(value)
    .split("\n")
    .map((line) => pad + line)
    .join("\n");
}

/** Renders a commented config.yaml for the given (validated) configuration. */
export function renderConfigYaml(config: DesignRailConfig): string {
  const c = config;
  return `# DesignRail configuration (schema version ${CONFIG_SCHEMA_VERSION}).
# Paths are relative to the project root. DesignRail reads this file as data only;
# it never executes project code or commands found in project files.
# Reference: docs/configuration.md in the DesignRail repository.
schemaVersion: ${CONFIG_SCHEMA_VERSION}

project:
  name: ${y(c.project.name)}
  # react | next | unknown (Next.js projects are also React projects)
  framework: ${c.project.framework}
  styling:
    # v3 | v4 | none — controls which Tailwind utility conventions the checker applies
    tailwind: ${c.project.styling.tailwind}
    css: ${c.project.styling.css}

source:
  # Files DesignRail checks. Secrets, node_modules, .git, build output, coverage, lockfiles,
  # and DesignRail's own reports/tasks are always skipped, even if matched here.
  include:
${block(c.source.include, 4)}
  exclude:
${block(c.source.exclude, 4)}
  # Import aliases (from tsconfig "paths"), used to resolve component imports for DR008.
  importAliases:${Object.keys(c.source.importAliases).length === 0 ? " {}" : `\n${block(c.source.importAliases, 4)}`}
  # Class-composition helpers whose static string arguments are analyzed.
  classFunctions: [${c.source.classFunctions.join(", ")}]

paths:
  tokens: ${c.paths.tokens}
  components: ${c.paths.components}
  designRules: ${c.paths.designRules}
  accessibilityRules: ${c.paths.accessibilityRules}
  productContext: ${c.paths.productContext}
  tasks: ${c.paths.tasks}

tokens:
  # Files that define tokens (for example the CSS file with :root variables).
  # Raw values are expected there, so DR001-DR003 do not report them.
  definitionFiles:${c.tokens.definitionFiles.length === 0 ? " []" : `\n${block(c.tokens.definitionFiles, 4)}`}

policies:
  # forbid: raw values need a token reference or an exception.
  # allow-matching-tokens: a raw value exactly equal to a token value passes.
  rawValues: ${c.policies.rawValues}
  # Pixels per rem when comparing values across units. null keeps px and rem distinct.
  remBasePx: ${c.policies.remBasePx === null ? "null" : c.policies.remBasePx}
  spacing:
    zero: ${c.policies.spacing.zero}          # allow | flag   (0, 0px)
    auto: ${c.policies.spacing.auto}          # allow | flag   (margin: auto)
    percentages: ${c.policies.spacing.percentages}   # allow | flag
    calc: ${c.policies.spacing.calc}   # tokens-only | allow | flag
  # Generic or fallback font families accepted after (or instead of) a font token.
  fontFallbacks: [${c.policies.fontFallbacks.map((f) => y(f)).join(", ")}]
  tailwind:
    # unknown: numeric utilities such as p-4 are reported as unverified coverage, not violations.
    # allow: Tailwind's numeric spacing scale is approved. flag: only token-backed spacing keys pass.
    numericSpacing: ${c.policies.tailwind.numericSpacing}
    # flag: default palette utilities such as bg-blue-500 are reported (DR001). allow: they pass.
    defaultPalette: ${c.policies.tailwind.defaultPalette}
  # DR005: forbid | allow-token-references | allow
  inlineStyles: ${c.policies.inlineStyles}
  # DR006 image elements. A component named "Image" imported from next/image is always checked.
  imageElements: [${c.policies.imageElements.join(", ")}]

# Enable/disable rules and override severities (error | warning | info).
rules:
${(Object.keys(c.rules) as (keyof DesignRailConfig["rules"])[])
  .map((id) => `  ${id}: { enabled: ${c.rules[id].enabled}, severity: ${c.rules[id].severity} }`)
  .join("\n")}

check:
  # Lowest severity that fails \`designrail check\`: error | warning | never.
  # --strict always fails on warnings too.
  failOn: ${c.check.failOn}

# Approved exceptions. Each needs a rule, a reason, and optionally files (globs) and values.
# Example:
#   - rule: DR001
#     files: ["src/legacy/**"]
#     values: ["#ff0000"]
#     reason: Legacy marketing page scheduled for redesign
exceptions:${c.exceptions.length === 0 ? " []" : `\n${block(c.exceptions, 2)}`}

responsive:
  # mobile-first | desktop-first | unspecified
  approach: ${c.responsive.approach}
  # Short project-specific guidance included in generated AI instructions.
  guidance:${c.responsive.guidance.length === 0 ? " []" : `\n${block(c.responsive.guidance, 4)}`}

# AI instruction targets generated by \`designrail sync\`: ${ADAPTER_IDS.join(" | ")}
# Optional "path" overrides the default file location.
adapters:
${block(c.adapters, 2)}

commands:
  # How this project runs DesignRail (shown to AI tools). DesignRail never runs these itself.
  check: ${y(c.commands.check)}
  projectChecks:${c.commands.projectChecks.length === 0 ? " []" : `\n${block(c.commands.projectChecks, 4)}`}

reports:
  enabled: ${c.reports.enabled}
  directory: ${c.reports.directory}
`;
}
