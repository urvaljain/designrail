export interface InitSettings {
  name?: string;
  framework?: DesignRailConfig["project"]["framework"];
  tailwind?: DesignRailConfig["project"]["styling"]["tailwind"];
  adapters?: AdapterId[];
  checkCommand?: string;
}

export type InitActionKind = "create" | "keep";

export interface InitAction {
  path: string;
  action: InitActionKind;
  note?: string;
}

export interface InitPlan {
  root: string;
  detection: Detection;
  existingConfig: boolean;
  config: DesignRailConfig;
  actions: InitAction[];
  /** Settings passed in but ignored because a valid configuration already exists. */
  ignoredSettings: string[];
}

export function configFromDetection(
  detection: Detection,
  settings: InitSettings,
  rootName: string,
): DesignRailConfig {
  const framework = settings.framework ?? (detection.framework === "unknown" ? "react" : detection.framework);
  return configSchema.parse({
    schemaVersion: CONFIG_SCHEMA_VERSION,
    project: {
      name: settings.name ?? detection.projectName ?? rootName,
      framework,
      styling: { tailwind: settings.tailwind ?? detection.tailwind, css: true },
    },
    source: {
      include: includePatternsFor(detection.sourceDirectories),
      importAliases: detection.importAliases,
    },
    adapters: (settings.adapters ?? ["codex", "claude-code"]).map((id) =>
      id === "claude-code" && detection.claudeInstructionsPath !== "CLAUDE.md"
        ? { id, path: detection.claudeInstructionsPath }
        : { id },
    ),
    commands: {
      check: settings.checkCommand ?? checkCommandFor(detection.packageManager, detection.scripts),
      projectChecks: projectChecksFor(detection.packageManager, detection.scripts),
    },
  });
}

export function parseAdapterList(value: string): AdapterId[] {
  const ids = value
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  const invalid = ids.filter((id) => !(ADAPTER_IDS as readonly string[]).includes(id));
  if (invalid.length > 0) {
    throw new Error(`Unknown adapter(s): ${invalid.join(", ")}. Choose from: ${ADAPTER_IDS.join(", ")}`);
  }
  return ids as AdapterId[];
}

const REPORTS_GITIGNORE = "# DesignRail reports are regenerated by `designrail check`.\n*\n!.gitignore\n";

/** Computes what init would do. Never modifies files. Throws if an existing config is invalid. */
export function planInit(cwd: string, settings: InitSettings = {}): InitPlan {
  const root = realRoot(cwd);
  const detection = detectProject(root);
  const existing = readConfig(root); // throws DesignRailError when invalid: init never replaces it
  const rootName = root.split(/[\\/]/).pop() || "project";
  const config = existing?.config ?? configFromDetection(detection, settings, rootName);
  validateConfigPaths(root, config);

  const ignoredSettings: string[] = [];
  if (existing) {
    for (const [key, value] of Object.entries(settings)) {
      if (value !== undefined) ignoredSettings.push(key);
    }
  }

  const files: { path: string; note?: string }[] = [
    { path: CONFIG_PATH },
    { path: config.paths.tokens, note: "unconfigured (no tokens yet)" },
    { path: config.paths.components, note: "empty registry" },
    { path: config.paths.designRules, note: "starter guidance" },
    { path: config.paths.accessibilityRules, note: "starter guidance" },
    { path: config.paths.productContext, note: "starter template" },
    { path: `${config.paths.tasks}/.gitkeep` },
    { path: `${config.reports.directory}/.gitignore` },
  ];
  const actions: InitAction[] = files.map((f) => {
    const { absolute } = resolveInsideRoot(root, f.path, "init path");
    return existsSync(absolute)
      ? { path: f.path, action: "keep", note: "already exists; left unchanged" }
      : { path: f.path, action: "create", ...(f.note ? { note: f.note } : {}) };
  });
  return { root, detection, existingConfig: existing !== null, config, actions, ignoredSettings };
}

function templateText(name: string): string {
  return readFileSync(join(packageRoot(), "templates", name), "utf8");
}

/** Creates the files marked "create" in the plan. Existing files are never overwritten. */
export function applyInit(plan: InitPlan): string[] {
  const created: string[] = [];
  const { config } = plan;
  const contentFor = (path: string): string => {
    if (path === CONFIG_PATH) return renderConfigYaml(config);
    if (path === config.paths.tokens) return serializeTokenFile(emptyTokenFile());
    if (path === config.paths.components) return serializeComponentFile(emptyComponentFile());
    if (path === config.paths.designRules) return templateText("design-rules.md");
    if (path === config.paths.accessibilityRules) return templateText("accessibility-rules.md");
    if (path === config.paths.productContext) return templateText("product-context.md");
    if (path.endsWith("/.gitignore")) return REPORTS_GITIGNORE;
    return "";
  };
  for (const action of plan.actions) {
    if (action.action !== "create") continue;
    atomicWrite(plan.root, action.path, contentFor(action.path), { mustNotExist: true });
    created.push(action.path);
  }
  return created;
}
